import { dash, formatDateLong, formatDateShort, initialsFromFullName } from "./format.js";
import { computeVat, moneyPhrase } from "./money.js";

function clientLabel(d) {
  if (d.clientType === "legal") {
    return dash(d.clientCompany, "________________________");
  }
  return dash(d.clientName, "________________________");
}

function clientShort(d) {
  if (d.clientType === "legal") return dash(d.clientCompany);
  return initialsFromFullName(d.clientName) || "____________________";
}

function citizenWord(d) {
  return d.gender === "female" ? "гражданка" : "гражданин";
}

function namedWord(d) {
  return d.gender === "female" ? "именуемая" : "именуемый";
}

function livingWord(d) {
  return d.gender === "female" ? "проживающая" : "проживающий";
}

export function vatClause(d) {
  const vat = computeVat(d.amount, d.vatMode);
  if (d.vatMode === "included20") {
    return `Стоимость услуг включает НДС по ставке 20 %: сумма без НДС — ${moneyPhrase(vat.net)}, НДС 20 % — ${moneyPhrase(vat.vat)}, итого — ${moneyPhrase(vat.gross)}.`;
  }
  if (d.vatMode === "onTop20") {
    return `НДС по ставке 20 % начисляется сверх стоимости услуг: сумма без НДС — ${moneyPhrase(vat.net)}, НДС 20 % — ${moneyPhrase(vat.vat)}, итого к оплате — ${moneyPhrase(vat.gross)}.`;
  }
  return "НДС не исчисляется. Если режим налогообложения Исполнителя изменится, Стороны подписывают дополнительное соглашение о порядке исчисления НДС.";
}

function passportBlock(d) {
  const issued = [
    d.passportIssuer ? dash(d.passportIssuer) : "",
    d.passportDate ? formatDateShort(d.passportDate) : "",
  ]
    .filter(Boolean)
    .join(", ");
  const parts = [`паспорт ${dash(d.passport)}`];
  if (issued) parts.push(`выдан ${issued}`);
  if (d.personalNumber) parts.push(`идентификационный номер ${dash(d.personalNumber)}`);
  return parts.join(", ");
}

export function buildPreamble(d) {
  const executor = `${d.executorName}, УНП ${d.executorUnp}, именуемое в дальнейшем «Исполнитель», в лице директора ${d.executorDirectorGenitive}, действующего на основании Устава`;

  if (d.clientType === "legal") {
    const director = dash(d.clientDirectorGenitive || d.clientDirector, "________________");
    return `${executor}, с одной стороны, и ${dash(d.clientCompany, "________________")}, УНП ${dash(d.clientUnp, "_________")}, именуемое в дальнейшем «Заказчик», в лице ${director}, действующего на основании ${dash(d.clientBasis, "Устава")}, с другой стороны, совместно именуемые «Стороны», заключили настоящий договор о нижеследующем.`;
  }

  return `${executor}, с одной стороны, и ${citizenWord(d)} ${clientLabel(d)}, ${passportBlock(d)}, ${livingWord(d)} по адресу: ${dash(d.clientAddress)}, ${namedWord(d)} в дальнейшем «Заказчик», с другой стороны, совместно именуемые «Стороны», заключили настоящий договор о нижеследующем.`;
}

function assignmentLine(d) {
  const bits = [];
  if (d.vehicleMake || d.vehicleModel) bits.push([d.vehicleMake, d.vehicleModel].filter(Boolean).join(" "));
  if (d.vehicleYearFrom || d.vehicleYearTo) {
    bits.push(
      `год выпуска ${d.vehicleYearFrom || "___"}${d.vehicleYearTo && d.vehicleYearTo !== d.vehicleYearFrom ? `–${d.vehicleYearTo}` : ""}`,
    );
  }
  if (d.vehicleBudget) bits.push(`максимальный бюджет лота ${d.vehicleBudget} ${d.vehicleBudgetCurrency || "EUR"}`);
  if (d.marketplace) bits.push(`площадки: ${d.marketplace}`);
  if (!bits.length) {
    return "Параметры подбора согласовываются Сторонами в приложении № 1 и (или) в заявке Заказчика.";
  }
  return `На дату заключения договора Заказчик ориентирует Исполнителя на следующие параметры подбора: ${bits.join("; ")}.`;
}

